/* PromptHub admin: edits a draft on this device and exports a new js/data.js */
async function startAdmin(){
const clone=o=>JSON.parse(JSON.stringify(o));
let draft=await idbGet(IDB_KEY);
if(!draft||!draft.prompts){
  /* one-time migration from the old localStorage-based draft, if present */
  try{const legacy=JSON.parse(localStorage.getItem("ph_admin_draft_v1"));if(legacy&&legacy.prompts){draft=legacy;await idbSet(IDB_KEY,draft);localStorage.removeItem("ph_admin_draft_v1")}}catch(e){}
}
if(!draft||!draft.prompts)draft={prompts:clone(PROMPTS),config:clone(CONFIG)};
draft.config.socials=draft.config.socials||{};
let editing=null,pendingImg="";
const msg=(t,bad)=>{const s=$("#st");s.textContent=t;s.style.color=bad?"#ff6b6b":"var(--mut)"};
async function persist(){
  const ok=await idbSet(IDB_KEY,draft);
  msg(ok?"Draft saved on this device. Download data.js to publish, or back it up as a .json file.":"Could not save your draft here. This browser may be blocking storage — back it up as a .json file now.",!ok);
}
const shrink=f=>new Promise((ok,no)=>{const r=new FileReader();r.onerror=no;r.onload=()=>{const i=new Image();i.onerror=no;i.onload=()=>{const s=Math.min(1,720/i.width),c=document.createElement("canvas");c.width=Math.round(i.width*s);c.height=Math.round(i.height*s);c.getContext("2d").drawImage(i,0,0,c.width,c.height);ok(c.toDataURL("image/jpeg",.74))};i.src=r.result};r.readAsDataURL(f)});

$("#aCat").innerHTML=CATS.map(c=>`<option>${c}</option>`).join("");
$("#aFile").onchange=async e=>{const f=e.target.files[0];if(!f)return;try{pendingImg=await shrink(f);$("#aPrev").src=pendingImg;$("#aPrev").classList.remove("hide")}catch(_){msg("Could not read that image. Try a JPG or PNG.",true)}};
function resetForm(){editing=null;pendingImg="";["aTitle","aTags","aPrompt","aFile","aPath"].forEach(i=>$("#"+i).value="");$("#aBadge").value="";$("#aPrev").classList.add("hide");$("#formTitle").textContent="Add a prompt";$("#save").textContent="Add prompt";$("#cancel").classList.add("hide")}
$("#cancel").onclick=resetForm;
$("#save").onclick=async()=>{
  const title=$("#aTitle").value.trim(),prompt=$("#aPrompt").value.trim();
  if(!title||!prompt)return msg("Add a title and the full prompt.",true);
  const old=editing!=null?draft.prompts.find(p=>p.id===editing):null;
  const image=pendingImg||$("#aPath").value.trim()||(old?old.image:"");
  const p={id:old?old.id:Math.max(0,...draft.prompts.map(x=>x.id))+1,title,image,category:$("#aCat").value,tags:$("#aTags").value.split(",").map(s=>s.trim().toLowerCase()).filter(Boolean),badge:$("#aBadge").value,prompt};
  if(old)draft.prompts[draft.prompts.indexOf(old)]=p;else draft.prompts.unshift(p);
  resetForm();await persist();draw();
};
function draw(){
  $("#cnt").textContent=draft.prompts.length;
  $("#list").innerHTML=draft.prompts.map(p=>`<div class="arow"><img src="${esc(img(p))}" alt=""><span>${esc(p.title)}</span><span class="mut">${esc(p.category)}</span><button type="button" data-act="edit" data-id="${p.id}">Edit</button><button type="button" data-act="del" data-id="${p.id}">Delete</button></div>`).join("")||`<p class="mut">No prompts yet. Add your first one.</p>`;
}
$("#list").onclick=async e=>{
  const b=e.target.closest("[data-act]");if(!b)return;const id=+b.dataset.id,p=draft.prompts.find(x=>x.id===id);if(!p)return;
  if(b.dataset.act==="del"){if(confirm("Delete \u201c"+p.title+"\u201d?")){draft.prompts=draft.prompts.filter(x=>x.id!==id);await persist();draw()}return}
  editing=id;pendingImg="";$("#aTitle").value=p.title;$("#aCat").value=p.category;$("#aBadge").value=p.badge||"";$("#aTags").value=(p.tags||[]).join(", ");$("#aPrompt").value=p.prompt;$("#aPath").value=p.image&&!p.image.startsWith("data:")?p.image:"";
  $("#formTitle").textContent="Edit prompt";$("#save").textContent="Save changes";$("#cancel").classList.remove("hide");window.scrollTo({top:0,behavior:"smooth"});
};
/* contact + social links */
$("#cMail").value=draft.config.email||"";$("#cWa").value=draft.config.whatsapp||"";
$("#cMail").oninput=e=>{draft.config.email=e.target.value.trim();persist()};
$("#cWa").oninput=e=>{draft.config.whatsapp=e.target.value.trim();persist()};
$("#socialInputs").innerHTML=SOCIALS.map(([n,u])=>`<div><label for="s-${n}">${n} URL</label><input id="s-${n}" data-soc="${n}" value="${esc(draft.config.socials[n]||u)}"></div>`).join("");
$("#socialInputs").oninput=e=>{const n=e.target.dataset.soc;if(n){draft.config.socials[n]=e.target.value.trim();persist()}};
/* export (publish) */
$("#dl").onclick=()=>{
  const cfg=clone(draft.config);
  const js=`/* PromptHub data. Generated by admin.html on ${new Date().toISOString().slice(0,10)}.\n   Replace js/data.js with this file, then redeploy. */\nvar CONFIG=${JSON.stringify(cfg,null,2)};\n\nvar PROMPTS=${JSON.stringify(draft.prompts,null,2)};\n`;
  const a=document.createElement("a");a.href=URL.createObjectURL(new Blob([js],{type:"text/javascript"}));a.download="data.js";document.body.appendChild(a);a.click();a.remove();
  msg("Downloaded data.js. Now replace js/data.js in your project with it and redeploy.");
};
/* backup / restore: a private safety copy of the whole draft, separate from publishing */
$("#backup").onclick=()=>{
  const payload={exported:new Date().toISOString(),prompts:draft.prompts,config:draft.config};
  const a=document.createElement("a");a.href=URL.createObjectURL(new Blob([JSON.stringify(payload,null,2)],{type:"application/json"}));a.download=`prompthub-backup-${Date.now()}.json`;document.body.appendChild(a);a.click();a.remove();
  msg("Backup downloaded. Keep it somewhere safe — Restore backup brings it back on any device.");
};
$("#restoreBtn").onclick=()=>$("#restoreFile").click();
$("#restoreFile").onchange=async e=>{
  const f=e.target.files[0];if(!f)return;
  try{
    const parsed=JSON.parse(await f.text());
    if(!parsed||!Array.isArray(parsed.prompts)||!parsed.config)throw new Error("bad shape");
    if(!confirm("Replace your current draft with this backup? This cannot be undone."))return;
    draft={prompts:parsed.prompts,config:parsed.config};
    draft.config.socials=draft.config.socials||{};
    await persist();draw();resetForm();
    $("#cMail").value=draft.config.email||"";$("#cWa").value=draft.config.whatsapp||"";
    $("#socialInputs").innerHTML=SOCIALS.map(([n,u])=>`<div><label for="s-${n}">${n} URL</label><input id="s-${n}" data-soc="${n}" value="${esc(draft.config.socials[n]||u)}"></div>`).join("");
    msg("Backup restored.");
  }catch(err){msg("That file doesn't look like a PromptHub backup.",true)}
  e.target.value="";
};
$("#discard").onclick=async()=>{if(confirm("Discard your draft and go back to the prompts currently in js/data.js?")){await idbDel(IDB_KEY);location.reload()}};
$("#lock").onclick=()=>{sessionStorage.removeItem("ph_admin_ok");location.reload()};
draw();
}

/* ===== sign-in gate =====
   Fixed admin email + phone (hashed in js/data.js as CONFIG.adminEmailHash / adminPhoneHash).
   This is a client-side deterrent, not real server security — see README. To change the
   login email/phone, generate new hashes the same way (see README) and update data.js. */
(function gate(){
  const g=s=>document.querySelector(s);
  const gm=t=>{g("#gMsg").textContent=t};
  const unlock=()=>{sessionStorage.setItem("ph_admin_ok","1");g("#gate").classList.add("hide");g("#app").classList.remove("hide");startAdmin()};
  if(sessionStorage.getItem("ph_admin_ok")==="1"){unlock();return}
  const SALT="prompthub:v1:";
  async function sha(s){if(!(window.crypto&&crypto.subtle))throw new Error("nocrypto");const b=await crypto.subtle.digest("SHA-256",new TextEncoder().encode(SALT+s));return [...new Uint8Array(b)].map(x=>x.toString(16).padStart(2,"0")).join("")}
  const go=async()=>{
    const email=(g("#gEmail").value||"").trim().toLowerCase();
    const phone=(g("#gPhone").value||"").replace(/\D/g,"");
    if(!email||!phone)return gm("Enter both the admin email and phone number.");
    try{
      const [eh,ph]=await Promise.all([sha("email:"+email),sha("phone:"+phone)]);
      if(eh===CONFIG.adminEmailHash&&ph===CONFIG.adminPhoneHash)unlock();
      else{gm("That email/phone doesn't match the admin account.");g("#gPhone").value=""}
    }catch(e){gm("This browser blocked secure sign-in. Open the page over https or from localhost.")}
  };
  g("#gGo").onclick=go;
  g("#gEmail").addEventListener("keydown",e=>{if(e.key==="Enter")g("#gPhone").focus()});
  g("#gPhone").addEventListener("keydown",e=>{if(e.key==="Enter")go()});
})();
